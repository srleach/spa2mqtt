#!/usr/bin/env python3
"""Generate esphome/packages/<definition>.yaml: every entity of a tub definition as spa_bus
platform entries, with names/icons/units from the definition.

    python3 tools/gen_esphome_package.py            # regenerate all
    python3 tools/gen_esphome_package.py --check    # CI: fail if any package is stale

Definitions whose protocol the spa_bus component does not implement are skipped: they are
bridge-only, and a package for them would compile into a device that mis-decodes.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "definitions"
PACKAGES = ROOT / "esphome" / "packages"
ESPHOME_PROTOCOLS = {"balboa_encrypted"}  # what esphome/components/spa_bus implements

HEADER = """\
# GENERATED by tools/gen_esphome_package.py from definitions/{src}. Do not edit by hand:
# change the definition and regenerate. Include it with `packages:` next to a `spa_bus:` hub;
# override any entity by re-declaring it with the same id in your device YAML.
"""


def entry(e: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {"platform": "spa_bus", "id": f"spa_{e['key']}", "entity": e["key"], "name": e["name"]}
    for src, dst in (
        ("icon", "icon"),
        ("entity_category", "entity_category"),
        ("device_class", "device_class"),
        ("unit_of_measurement", "unit_of_measurement"),
        ("state_class", "state_class"),
        ("accuracy_decimals", "accuracy_decimals"),
        ("mode", "mode"),
    ):
        if src in e:
            out[dst] = e[src].upper() if src == "mode" else e[src]
    if e.get("enabled_by_default") is False:
        out["disabled_by_default"] = True
    return out


def render(path: Path) -> str | None:
    """The package text, or None when ESPHome does not support the definition's protocol."""
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if raw.get("protocol") not in ESPHOME_PROTOCOLS:
        return None
    groups: dict[str, list[dict[str, Any]]] = {}
    for e in raw["entities"]:
        groups.setdefault(e["component"], []).append(entry(e))
    body = yaml.safe_dump(groups, sort_keys=False, allow_unicode=True, width=120)
    return HEADER.format(src=path.name) + body


def main() -> int:
    check = "--check" in sys.argv
    PACKAGES.mkdir(parents=True, exist_ok=True)
    stale = []
    for path in sorted(DEFINITIONS.glob("*.yaml")):
        target = PACKAGES / path.name
        text = render(path)
        if text is None:
            print(f"skipped {path.name}: protocol not supported by the ESPHome component (bridge only)")
            if target.is_file():
                if check:
                    stale.append(target.name)
                else:
                    target.unlink()
                    print(f"removed {target.relative_to(ROOT)}")
            continue
        if check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                stale.append(target.name)
        else:
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print(f"stale ESPHome packages (run tools/gen_esphome_package.py): {stale}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
